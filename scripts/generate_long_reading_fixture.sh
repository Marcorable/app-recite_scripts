#!/bin/bash
# 저작권·개인정보가 없는 5분 이상 낭독용 중립 대본을 표준 출력으로 만든다.
set -euo pipefail

sentences=(
    "오늘은 창문을 열고 천천히 하루를 시작한다."
    "책상 위의 연필과 공책을 가지런히 정리한다."
    "따뜻한 물을 마시고 편안하게 숨을 고른다."
    "밝은 햇살이 방 안으로 조용히 들어온다."
    "한 문장씩 또렷하게 읽으며 순서를 확인한다."
    "잠시 쉬었다가 같은 속도로 다음 문장을 읽는다."
    "마지막까지 서두르지 않고 자연스럽게 이어간다."
    "모든 문장을 읽은 뒤 오늘의 연습을 마친다."
)

for _ in $(seq 1 12); do
    printf '%s ' "${sentences[@]}"
done
printf '\n'
